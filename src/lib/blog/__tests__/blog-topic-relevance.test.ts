import { describe, expect, it } from "vitest";
import {
  matchTopicCompares,
  matchTopicPages,
  mentions,
  topicKeywords,
} from "@/lib/blog/blog-topic-relevance";
import { decideBuildRoute } from "@/lib/generation/build-route";

describe("ROO-234 topic keywords", () => {
  it("keeps topic words and drops filler", () => {
    expect(topicKeywords("free-vs-paid-password-managers-guide")).toEqual(["password", "manager"]);
    expect(topicKeywords("how-to-improve-pc-gaming-performance")).toContain("gaming");
    expect(topicKeywords("how-to-improve-pc-gaming-performance")).not.toContain("improve");
  });
});

describe("ROO-234 topic pages", () => {
  it("sends the password-manager post to the password hub", () => {
    const [first] = matchTopicPages(topicKeywords("free-vs-paid-password-managers-guide"));
    expect(first?.href).toMatch(/password-manager/);
  });

  it("matches nothing for a post with no topic page", () => {
    expect(matchTopicPages(topicKeywords("epipen-cost-without-insurance"))).toEqual([]);
  });
});

describe("ROO-234 topic compares", () => {
  it("finds 1password-vs-bitwarden from 'password' and keeps only live ones", async () => {
    const links = await matchTopicCompares(["password", "manager"], {
      search: async (q) =>
        q === "password"
          ? [
              { slug: "1password-vs-bitwarden", title: "1Password vs Bitwarden" },
              { slug: "dashlane-vs-lastpass", title: "Dashlane vs LastPass password manager" },
            ]
          : [],
      filterLive: async (slugs) => slugs.filter((s) => s !== "dashlane-vs-lastpass"),
    });
    expect(links).toEqual([{ slug: "1password-vs-bitwarden", title: "1Password vs Bitwarden" }]);
  });

  it("does not count a search hit that never mentions the keyword", async () => {
    const links = await matchTopicCompares(["epipen"], {
      search: async () => [{ slug: "lebron-vs-jordan", title: "LeBron vs Jordan" }],
      filterLive: async (s) => s,
    });
    expect(links).toEqual([]);
  });

  it("ignores hits that only match a minor keyword", async () => {
    const links = await matchTopicCompares(["calorie", "fitness", "galaxy"], {
      search: async () => [{ slug: "galaxy-s25-vs-galaxy-s25-fe", title: "Galaxy S25 vs Galaxy S25 FE" }],
      filterLive: async (s) => s,
    });
    expect(links).toEqual([]);
  });

  it("treats premium and ticket as filler", () => {
    expect(topicKeywords("imax-vs-dolby-cinema-2026-is-the-premium-ticket-worth-it")).not.toContain("premium");
  });

  it("matches whole words, or glued brand words of 6+ letters", () => {
    expect(mentions({ slug: "airpods-vs-galaxy-buds", title: "" }, "air")).toBe(false);
    expect(mentions({ slug: "1password-vs-bitwarden", title: "" }, "password")).toBe(true);
  });
});

describe("ROO-234 /build route decision", () => {
  const deps = {
    generationEnabled: () => true,
    filterLive: async () => [] as string[],
    rowMetadata: async () => null,
  };

  it("builds a valid missing pair under its canonical slug", async () => {
    expect(await decideBuildRoute("imax-vs-dolby-cinema", deps)).toEqual({ kind: "build", slug: "dolby-cinema-vs-imax" });
  });

  it("redirects a live pair", async () => {
    expect(
      await decideBuildRoute("gog-vs-steam", { ...deps, filterLive: async () => ["gog-vs-steam"] }),
    ).toEqual({ kind: "live", slug: "gog-vs-steam" });
  });

  it("404s when generation is off, the row is held back, or the slug is junk", async () => {
    expect(await decideBuildRoute("imax-vs-dolby-cinema", { ...deps, generationEnabled: () => false })).toEqual({
      kind: "not_found",
    });
    expect(
      await decideBuildRoute("imax-vs-dolby-cinema", {
        ...deps,
        rowMetadata: async () => ({ status: "draft", isAutoGenerated: false }),
      }),
    ).toEqual({ kind: "not_found" });
    expect(await decideBuildRoute("imax-vs-imax", deps)).toEqual({ kind: "not_found" });
    expect(await decideBuildRoute("not-a-pair", deps)).toEqual({ kind: "not_found" });
  });
});
