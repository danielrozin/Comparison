/**
 * JSON-LD @id edges must point at a node in the same page graph.
 * A compare with no FAQs emits neither an FAQPage nor a #faq link.
 */
import { beforeAll, describe, expect, it, vi } from "vitest";
import { render } from "@testing-library/react";

vi.mock("next/navigation", () => ({
  useRouter: () => ({ push: () => {}, replace: () => {}, prefetch: () => {} }),
  useSearchParams: () => new URLSearchParams(),
  usePathname: () => "/category/products/ereaders",
  notFound: () => {
    throw new Error("NEXT_NOT_FOUND");
  },
}));
import type { ComparisonPageData, ComparisonEntityData } from "@/types";
import { assembleCompareJsonLd } from "@/lib/seo/compare-jsonld";
import { BRAVE_VS_CHROME } from "@/lib/data/editorial-compares/brave-vs-chrome";
import { HUB_CONFIG } from "@/lib/data/hubs";
