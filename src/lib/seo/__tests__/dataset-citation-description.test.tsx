/**
 * Coverage for datasetCitationDescription and the two Dataset call sites.
 * Fixtures are synthetic. They are not product facts.
 */
import { cleanup, render, screen } from "@testing-library/react";
import { afterEach, describe, expect, it } from "vitest";
import { CitationStatsBar } from "@/components/comparison/CitationStatsBar";
import type { CitationStats, ComparisonAttribute, ComparisonEntityData, ComparisonPageData } from "@/types";
import { comparisonPageSchema, datasetCitationDescription } from "../schema";

function citation(
  overrides: Partial<CitationStats> = {},
): { sourceCount: number; dataPointCount: number; reviewsAnalyzed?: number | null } {
  return {
    sourceCount: 3,
    dataPointCount: 12,
    reviewsAnalyzed: null,
    ...overrides,
  };
}

function entity(position: number, name: string): ComparisonEntityData {
  const slug = name.toLowerCase().replace(/\s+/g, "-");
  return {
    id: `fixture-${position}`,
    slug,
    name,
    shortDesc: null,
    imageUrl: null,
    entityType: "product",
    position,
    pros: [],
    cons: [],
    bestFor: null,
  };
}

function page(entities: ComparisonEntityData[], stats: CitationStats): ComparisonPageData {
  const attribute: ComparisonAttribute = {
    id: "fixture-row",
    slug: "fixture-row",
    name: "Fixture row",
    unit: null,
    category: "Specs",
    dataType: "text",
    higherIsBetter: null,
    values: entities.map((item) => ({
      entityId: item.id,
      valueText: "synthetic",
      valueNumber: null,
      valueBoolean: null,
    })),
  };
  return {
    id: "fixture-comparison",
    slug: "fixture-alpha-vs-fixture-beta",
    title: "Fixture comparison",
    shortAnswer: "Synthetic short answer.",
    keyDifferences: [],
    verdict: null,
    category: "technology",
    entities,
    attributes: [attribute],
    faqs: [],
    relatedComparisons: [],
    relatedBlogPosts: [],
    citationStats: stats,
    metadata: {
      metaTitle: "Fixture comparison",
      metaDescription: "Synthetic description for the dataset helper test.",
      publishedAt: "2026-01-15T00:00:00.000Z",
      updatedAt: "2026-01-15T00:00:00.000Z",
      isAutoGenerated: false,
      isHumanReviewed: false,
      viewCount: 0,
    },
  };
}

function stats(overrides: Partial<CitationStats> = {}): CitationStats {
  return {
    sourceCount: 3,
    dataPointCount: 12,
    reviewsAnalyzed: null,
    preferencePercent: null,
    preferenceEntity: null,
    lastResearched: "2026-01-15T00:00:00.000Z",
    sources: [],
    ...overrides,
  };
}

function datasetDescription(comparison: ComparisonPageData): string {
  const schemas = comparisonPageSchema(comparison) as Array<{
    "@type"?: string;
    description?: string;
    "@graph"?: Array<{ "@type"?: string; description?: string }>;
  }>;
  for (const node of schemas) {
    if (node["@type"] === "Dataset" && typeof node.description === "string") return node.description;
    const nested = node["@graph"]?.find((child) => child["@type"] === "Dataset");
    if (nested && typeof nested.description === "string") return nested.description;
  }
  throw new Error("comparisonPageSchema did not emit a Dataset");
}

describe("datasetCitationDescription", () => {
  it("includes a positive data-point count and omits zero or negative counts", () => {
    const covered = "Fixture North vs Fixture South";
    expect(datasetCitationDescription(citation({ dataPointCount: 12 }), covered, false)).toBe(
      "Structured side-by-side comparison dataset based on 3 sources and 12 data points, covering Fixture North vs Fixture South attribute by attribute.",
    );
    expect(datasetCitationDescription(citation({ dataPointCount: 0 }), covered, false)).toBe(
      "Structured side-by-side comparison dataset based on 3 sources, covering Fixture North vs Fixture South attribute by attribute.",
    );
    expect(datasetCitationDescription(citation({ dataPointCount: -4 }), covered, false)).toBe(
      "Structured side-by-side comparison dataset based on 3 sources, covering Fixture North vs Fixture South attribute by attribute.",
    );
  });

  it("adds a positive review count only when includeReviews is true", () => {
    const covered = "Fixture North vs Fixture South";
    const withReviews = citation({ reviewsAnalyzed: 17 });
    expect(datasetCitationDescription(withReviews, covered, true)).toContain(", analyzing 17 reviews,");
    expect(datasetCitationDescription(withReviews, covered, false)).not.toContain("reviews");
    expect(datasetCitationDescription(citation({ reviewsAnalyzed: null }), covered, true)).not.toContain("reviews");
    expect(datasetCitationDescription(citation({ reviewsAnalyzed: 0 }), covered, true)).not.toContain("reviews");
  });

  it("keeps a zero source count in the sentence and does not invent sources", () => {
    const description = datasetCitationDescription(
      citation({ sourceCount: 0, dataPointCount: 0, reviewsAnalyzed: null }),
      "Fixture North vs Fixture South",
      true,
    );
    expect(description).toBe(
      "Structured side-by-side comparison dataset based on 0 sources, covering Fixture North vs Fixture South attribute by attribute.",
    );
    expect(description).not.toContain("0 data points");
    expect(description).not.toMatch(/http|study|opened/i);
  });
});

describe("comparisonPageSchema Dataset description", () => {
  const pair = [entity(0, "Fixture North"), entity(1, "Fixture South")];
  const trio = [...pair, entity(2, "Fixture East")];

  it("uses the two-entity call path, including a positive review count", () => {
    const description = datasetDescription(
      page(pair, stats({ sourceCount: 3, dataPointCount: 12, reviewsAnalyzed: 17 })),
    );
    expect(description).toBe(
      "Structured side-by-side comparison dataset based on 3 sources and 12 data points, analyzing 17 reviews, covering Fixture North vs Fixture South attribute by attribute.",
    );
  });

  it("uses the three-entity call path: comma-separated names and no review clause", () => {
    const description = datasetDescription(
      page(trio, stats({ sourceCount: 3, dataPointCount: 12, reviewsAnalyzed: 17 })),
    );
    expect(description).toBe(
      "Structured side-by-side comparison dataset based on 3 sources and 12 data points, covering Fixture North, Fixture South, Fixture East attribute by attribute.",
    );
    expect(description).not.toContain("reviews");
    expect(description).not.toContain(" vs ");
  });

  it("keeps sourceCount 0 on the generated two-entity description", () => {
    const description = datasetDescription(
      page(pair, stats({ sourceCount: 0, dataPointCount: 0, reviewsAnalyzed: null, sources: [] })),
    );
    expect(description).toContain("based on 0 sources");
    expect(description).not.toContain("0 data points");
    expect(description).not.toContain("Fixture catalog");
  });
});

describe("CitationStatsBar", () => {
  afterEach(() => {
    cleanup();
  });

  it("shows positive source and data-point counts and hides zeros", () => {
    render(<CitationStatsBar stats={stats({ sourceCount: 4, dataPointCount: 9, sources: [] })} />);
    expect(screen.getByText("4")).toBeInTheDocument();
    expect(screen.getByText("Sources")).toBeInTheDocument();
    expect(screen.getByText("9")).toBeInTheDocument();
    expect(screen.getByText("Data Points")).toBeInTheDocument();
    cleanup();

    render(<CitationStatsBar stats={stats({ sourceCount: 4, dataPointCount: 0, sources: [] })} />);
    expect(screen.getByText("Sources")).toBeInTheDocument();
    expect(screen.getByText("4")).toBeInTheDocument();
    expect(screen.queryByText("Data Points")).not.toBeInTheDocument();
    cleanup();

    const { container } = render(
      <CitationStatsBar stats={stats({ sourceCount: 0, dataPointCount: 0, reviewsAnalyzed: 0, sources: [] })} />,
    );
    expect(container).toBeEmptyDOMElement();
    expect(screen.queryByText("Sources")).not.toBeInTheDocument();
    expect(screen.queryByText("Data Points")).not.toBeInTheDocument();
  });
});
