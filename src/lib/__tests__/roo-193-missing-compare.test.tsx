import { describe, expect, it, vi, beforeEach, afterEach } from "vitest";
import { act, render, screen } from "@testing-library/react";
import type { ReactNode } from "react";
import {
  blocksOnDemandBuild,
  decideComparePage,
  isRebuildableArchivedRow,
} from "@/lib/compare-slug-resolution";
import { classifyMissingLandingReferrer } from "@/lib/analytics/missing-comparison-landing";
import { isNotFoundDocument } from "@/lib/analytics/comparison-view-capture";

vi.mock("next/head", () => ({ default: ({ children }: { children: unknown }) => children }));
vi.mock("next/link", () => ({
  default: ({ href, children }: { href: string; children?: ReactNode }) => <a href={href}>{children}</a>,
}));
vi.mock("@/lib/utils/analytics", () => ({
  trackCompareNotFound: vi.fn(),
  trackGenerationRequested: vi.fn(),
}));
const automation = vi.hoisted(() => ({ headless: false }));
vi.mock("@/lib/analytics/automated-client", () => ({
  isHeadlessAutomationClient: () => automation.headless,
}));

import { OnDemandComparison } from "@/components/comparison/OnDemandComparison";

describe("ROO-193 rebuildable archived rows", () => {
  it("auto-generated archived rows do not block the builder", () => {
    expect(isRebuildableArchivedRow({ status: "archived", isAutoGenerated: true })).toBe(true);
    expect(blocksOnDemandBuild({ status: "archived", isAutoGenerated: true })).toBe(false);
  });
  it("draft, review and hand-written archived rows stay hidden", () => {
    expect(blocksOnDemandBuild({ status: "draft", isAutoGenerated: true })).toBe(true);
    expect(blocksOnDemandBuild({ status: "review" })).toBe(true);
    expect(blocksOnDemandBuild({ status: "archived", isAutoGenerated: false })).toBe(true);
    expect(blocksOnDemandBuild(null)).toBe(false);
  });
  it("a missing or rebuildable pair resolves to the builder shell, not a hard 404", () => {
    expect(decideComparePage("deel-vs-remote", () => "missing")).toEqual({ action: "shell", slug: "deel-vs-remote" });
    expect(decideComparePage("deel-vs-remote", () => "hidden")).toEqual({ action: "not_found" });
  });
});

describe("missing_comparison_landing referrer_type", () => {
  const host = "www.aversusb.net";
  it.each([
    ["https://www.google.com/", false, "search_engine"],
    ["https://duckduckgo.com/", false, "search_engine"],
    ["https://chatgpt.com/", false, "ai_assistant"],
    ["https://www.perplexity.ai/search", false, "ai_assistant"],
    ["https://gemini.google.com/app", false, "ai_assistant"],
    ["https://www.aversusb.net/blog/x", false, "internal"],
    ["https://news.ycombinator.com/", false, "external"],
    ["", false, "direct"],
    ["https://www.google.com/", true, "internal_search"],
  ])("%s (from_search=%s) -> %s", (ref, fromSearch, expected) => {
    expect(classifyMissingLandingReferrer(ref as string, host, fromSearch as boolean)).toBe(expected);
  });
});

describe("comparison_viewed is not fired on not-found pages", () => {
  function doc(page: string) {
    return { getElementById: () => ({ textContent: JSON.stringify({ page }) }) } as unknown as Document;
  }
  it("detects the 404 document", () => {
    expect(isNotFoundDocument(doc("/404"))).toBe(true);
    expect(isNotFoundDocument(doc("/compare/[slug]"))).toBe(false);
    expect(isNotFoundDocument(null)).toBe(false);
  });
});

describe("OnDemandComparison", () => {
  const related = [{ slug: "usa-vs-china", title: "USA vs China" }];
  let ua: PropertyDescriptor | undefined;
  beforeEach(() => {
    ua = Object.getOwnPropertyDescriptor(window.navigator, "userAgent");
    automation.headless = false;
  });
  afterEach(() => {
    if (ua) Object.defineProperty(window.navigator, "userAgent", ua);
    vi.unstubAllGlobals();
  });

  it("shows free related compares while building and never Pro pricing", async () => {
    Object.defineProperty(window.navigator, "userAgent", { value: "Mozilla/5.0 (Macintosh) Chrome/130", configurable: true });
    vi.stubGlobal("fetch", vi.fn(() => new Promise(() => {})));
    render(<OnDemandComparison slug="deel-vs-remote" entityA="Deel" entityB="Remote" initialRelated={related} />);
    expect(screen.getByText(/building your comparison/)).toBeInTheDocument();
    expect(screen.getByRole("link", { name: "USA vs China" })).toHaveAttribute("href", "/compare/usa-vs-china");
    expect(screen.queryByText(/Pro pricing/)).not.toBeInTheDocument();
  });

  it("skips generation for crawlers but still renders the page", async () => {
    Object.defineProperty(window.navigator, "userAgent", { value: "Mozilla/5.0 (compatible; GPTBot/1.2)", configurable: true });
    const fetchMock = vi.fn();
    vi.stubGlobal("fetch", fetchMock);
    await act(async () => {
      render(<OnDemandComparison slug="deel-vs-remote" entityA="Deel" entityB="Remote" initialRelated={related} />);
    });
    expect(fetchMock).not.toHaveBeenCalled();
    expect(screen.getByRole("heading", { name: "Deel vs Remote" })).toBeInTheDocument();
    expect(screen.getByRole("link", { name: "USA vs China" })).toBeInTheDocument();
  });

  it("shows related compares when the daily cap refuses the build", async () => {
    Object.defineProperty(window.navigator, "userAgent", { value: "Mozilla/5.0 (Macintosh) Chrome/130", configurable: true });
    vi.stubGlobal(
      "fetch",
      vi.fn(async (url: string) =>
        String(url).includes("/generate")
          ? { status: 429, ok: false, json: async () => ({ reason: "global_day" }) }
          : { status: 200, ok: true, json: async () => ({ comparisons: [] }) },
      ),
    );
    render(<OnDemandComparison slug="deel-vs-remote" entityA="Deel" entityB="Remote" initialRelated={related} />);
    expect(await screen.findByText(/as many new comparisons as we can today/)).toBeInTheDocument();
    expect(screen.getByRole("link", { name: "USA vs China" })).toBeInTheDocument();
    expect(screen.queryByText(/Pro pricing/)).not.toBeInTheDocument();
  });
});
