/**
 * ROO-234: the /build/<slug> page, the 200 entry point to the ROO-193
 * on-demand builder.
 *
 * A missing /compare URL answers HTTP 404 (it shows the builder after
 * hydration), so a blog card cannot link it without failing the ROO-224
 * "never link a 404" check. /build/<slug> answers 200 only when the builder
 * would actually build the pair. The blog page runs this same decision
 * before it links, so a card never links a /build URL that 404s.
 *
 * Generation itself is unchanged: the page posts to /api/comparisons/generate,
 * which keeps its own quality gate (2+ sources) and caps.
 */

import { canRequestComparisonSlug, canonicalRequestedComparisonSlug } from "@/lib/parse-comparison-query";
import { isUserGenerationEnabled, queryBlockReason } from "@/lib/generation/user-generation-guard";
import { blocksOnDemandBuild, relatedComparisonSlugs } from "@/lib/compare-slug-resolution";

export type BuildRouteDecision =
  | { kind: "build"; slug: string }
  | { kind: "live"; slug: string }
  | { kind: "not_found" };

export interface BuildRouteDeps {
  generationEnabled: () => boolean;
  /** Live (200) compare slugs among the candidates, canonical form. */
  filterLive: (slugs: string[]) => Promise<string[]>;
  /** Lifecycle metadata of a row with this slug, or null when there is none. */
  rowMetadata: (slug: string) => Promise<{ status?: string | null; isAutoGenerated?: boolean | null } | null | undefined>;
}

export async function decideBuildRoute(rawSlug: string, deps: BuildRouteDeps): Promise<BuildRouteDecision> {
  const slug = (rawSlug || "").toLowerCase();
  if (!/^[a-z0-9-]+-vs-[a-z0-9-]+$/.test(slug)) return { kind: "not_found" };
  const canonical = canonicalRequestedComparisonSlug(slug);
  if (!canonical || !canRequestComparisonSlug(canonical)) return { kind: "not_found" };
  const [a, b] = canonical.split("-vs-");
  if (!a || !b || queryBlockReason(a.replace(/-/g, " "), b.replace(/-/g, " "))) return { kind: "not_found" };

  const live = await deps.filterLive(Array.from(new Set([slug, canonical])));
  if (live.length > 0) return { kind: "live", slug: live[0] };

  if (!deps.generationEnabled()) return { kind: "not_found" };

  const rows = await Promise.all(
    relatedComparisonSlugs(canonical).map((candidate) => deps.rowMetadata(candidate).catch(() => null)),
  );
  // Archived / draft / review rows are held back on purpose: no builder.
  if (rows.some((meta) => blocksOnDemandBuild(meta ?? undefined))) return { kind: "not_found" };
  return { kind: "build", slug: canonical };
}

/** Production wiring, shared by the page and the blog card. */
export async function decideBuildRouteLive(slug: string): Promise<BuildRouteDecision> {
  const [{ filterLiveCompareSlugs }, { getComparisonBySlug }] = await Promise.all([
    import("@/lib/seo/resolve-internal-links"),
    import("@/lib/services/comparison-service"),
  ]);
  return decideBuildRoute(slug, {
    generationEnabled: isUserGenerationEnabled,
    filterLive: filterLiveCompareSlugs,
    rowMetadata: async (candidate) => (await getComparisonBySlug(candidate))?.metadata ?? null,
  });
}
