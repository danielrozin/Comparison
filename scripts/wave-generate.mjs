/**
 * Wave generation — ask production to generate each queued comparison.
 *
 *   node scripts/wave-generate.mjs scripts/data/wave-queue-2026-08-30.json          # every queue slug
 *   node scripts/wave-generate.mjs scripts/data/wave-queue-2026-08-30.json 0 20     # slice [0,20)
 *   node scripts/wave-generate.mjs --slugs a-vs-b c-vs-d                             # ad hoc
 *
 * Uses POST /api/comparisons/generate on the live site rather than calling the
 * generator locally: that route is the canonical path (DAN-1265 duplicate
 * guards, DAN-2324 suffix guard, attempt tracking, the same model + Tavily
 * enrichment the on-demand pages get) and the local DATABASE_URL is stale.
 *
 * Generated pages land as status "archived" (DAN-1886: auto-generated content
 * never publishes without review). Review + publish is scripts/wave-publish.mjs
 * via the "Wave publish" workflow.
 *
 * Results append to scripts/data/wave-run-<date>.json so a rerun skips
 * anything already generated.
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import './lib/env.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const SITE = process.env.PUBLISH_SOURCE_ORIGIN || 'https://www.aversusb.net';
const DATE = new Date().toISOString().slice(0, 10);
const RUN = path.join(here, 'data', `wave-run-${DATE}.json`);

const args = process.argv.slice(2);
let slugs;
if (args[0] === '--slugs') slugs = args.slice(1);
else {
  const q = JSON.parse(fs.readFileSync(args[0], 'utf-8'));
  const from = Number(args[1] ?? 0), to = Number(args[2] ?? q.queue.length);
  slugs = q.queue.slice(from, to).map((c) => c.slug);
}
if (!slugs?.length) { console.error('Usage: wave-generate.mjs <queue.json> [from] [to] | --slugs <slug...>'); process.exit(1); }

const run = fs.existsSync(RUN) ? JSON.parse(fs.readFileSync(RUN, 'utf-8')) : { startedAt: new Date().toISOString(), site: SITE, results: {} };
const save = () => fs.writeFileSync(RUN, JSON.stringify(run, null, 1));

for (const slug of slugs) {
  if (run.results[slug]?.status === 'ready') { console.log(`  = done: ${slug}`); continue; }
  const t0 = Date.now();
  let res, body;
  try {
    res = await fetch(`${SITE}/api/comparisons/generate`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ slug }),
      signal: AbortSignal.timeout(90_000),
    });
    body = await res.json().catch(() => ({}));
  } catch (e) {
    body = { status: 'error', error: e.message };
  }
  const secs = ((Date.now() - t0) / 1000).toFixed(0);
  const c = body.comparison;
  const entry = {
    status: body.status || 'error',
    http: res?.status ?? 0,
    canonicalSlug: body.canonicalSlug || null,
    error: body.error || null,
    errorStage: body.errorStage || null,
    title: c?.title || null,
    entities: c?.entities?.length ?? null,
    keyDifferences: c?.keyDifferences?.length ?? null,
    faqs: c?.faqs?.length ?? null,
    shortAnswer: c?.shortAnswer?.slice(0, 160) || null,
    isAutoGenerated: c?.metadata?.isAutoGenerated ?? null,
    secs: Number(secs),
    at: new Date().toISOString(),
  };
  run.results[slug] = entry;
  save();
  const mark = entry.status === 'ready' ? '✓' : entry.status === 'in_progress' ? '…' : '!';
  console.log(`  ${mark} ${slug} — ${entry.status}${entry.canonicalSlug && entry.canonicalSlug !== slug ? ` (→ ${entry.canonicalSlug})` : ''} ${entry.error ? `— ${entry.error}` : `— ${entry.entities} entities, ${entry.keyDifferences} diffs, ${entry.faqs} faqs`} [${secs}s]`);
  // "in_progress" = a concurrent attempt is running; give it time then re-poll once.
  if (entry.status === 'in_progress') {
    await new Promise((r) => setTimeout(r, 60_000));
    slugs.push(slug);
  }
}

const tally = Object.values(run.results).reduce((t, r) => ((t[r.status] = (t[r.status] || 0) + 1), t), {});
console.log(`\n${JSON.stringify(tally)} → ${path.relative(process.cwd(), RUN)}`);
