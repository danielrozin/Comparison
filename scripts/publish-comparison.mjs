/**
 * Publish a comparison into the real catalogue so its page renders.
 *
 *   node scripts/publish-comparison.mjs haaland-vs-mbappe
 *   node scripts/publish-comparison.mjs --dry-run slug-a slug-b
 *
 * Why this exists
 * ---------------
 * `/api/video-pipeline/slugs` is built from `getAllMockSlugs()` — 141 slugs —
 * but `/compare/<slug>` renders only rows whose `Comparison.status` is
 * "published" (isRenderableComparison in src/pages/compare/[slug].tsx,
 * DAN-2065). Mock fixtures carry no status, so 73 of those 141 slugs 404 in
 * production while still being advertised to the video pipeline. A video was
 * published for one of them (haaland-vs-mbappe) pointing at a dead page.
 *
 * This closes the gap in the honest direction: rather than letting pages
 * render straight from dev fixtures — the leak DAN-2065 deliberately shut —
 * it promotes a fixture's content into the database as a genuine published
 * comparison, so the catalogue and the pages agree.
 *
 * Content comes from /api/video-pipeline/data, which reads the same source, so
 * this script needs no TypeScript loader and cannot drift from the app's own
 * shape. It does need a working DATABASE_URL — the local one is stale, so it
 * normally runs through the publish-comparison workflow.
 */

import { PrismaClient } from '@prisma/client';
import './lib/env.mjs';

const prisma = new PrismaClient();

const args = process.argv.slice(2);
const dryRun = args.includes('--dry-run');
const slugs = args.filter((a) => !a.startsWith('--'));
const SITE = process.env.PUBLISH_SOURCE_ORIGIN || 'https://www.aversusb.net';

if (!slugs.length) {
  console.error('Usage: node scripts/publish-comparison.mjs [--dry-run] <slug> [slug...]');
  process.exit(1);
}

const slugify = (s) =>
  String(s)
    .toLowerCase()
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');

async function fetchComparison(slug) {
  const res = await fetch(`${SITE}/api/video-pipeline/data?slug=${encodeURIComponent(slug)}`, {
    signal: AbortSignal.timeout(20_000),
  });
  if (!res.ok) throw new Error(`data API returned ${res.status}`);
  return res.json();
}

async function ensureEntityType(typeSlug) {
  const slug = slugify(typeSlug || 'thing') || 'thing';
  const existing = await prisma.entityType.findUnique({ where: { slug } });
  if (existing) return existing;
  return prisma.entityType.create({
    data: { slug, name: slug.charAt(0).toUpperCase() + slug.slice(1) },
  });
}

async function ensureEntity(entity, typeId) {
  const slug = entity.slug || slugify(entity.name);
  const existing = await prisma.entity.findUnique({ where: { slug } });
  if (existing) {
    console.log(`    entity  ${slug} (existing)`);
    return existing;
  }
  const created = await prisma.entity.create({
    data: {
      slug,
      name: entity.name,
      shortDesc: entity.shortDesc ?? null,
      imageUrl: entity.imageUrl ?? null,
      entityTypeId: typeId,
      status: 'published',
      publishedAt: new Date(),
    },
  });
  console.log(`    entity  ${slug} (created)`);
  return created;
}

async function publish(slug) {
  console.log(`\n=== ${slug} ===`);

  const existing = await prisma.comparison.findUnique({
    where: { slug },
    select: {
      id: true,
      status: true,
      title: true,
      isAutoGenerated: true,
      isHumanReviewed: true,
      _count: { select: { entities: true } },
    },
  });
  if (existing?.status === 'published') {
    console.log('    already published — nothing to do');
    return 'skipped';
  }

  // A row that already exists with both entities needs a status change, not a
  // content import. Sourcing from the fixture API would fail for these: most
  // archived rows were never mock fixtures, so the API 404s on them even
  // though the comparison is complete in the database.
  if (existing && existing._count.entities >= 2) {
    console.log(`    title   ${existing.title}`);
    console.log(`    exists with status "${existing.status}", ${existing._count.entities} entities`);
    if (existing.isAutoGenerated && !existing.isHumanReviewed) {
      console.log('    NOTE: auto-generated and never human-reviewed. It was archived');
      console.log('          by DAN-1886 for that reason. Read the page before trusting it.');
    }
    if (dryRun) {
      console.log('    DRY RUN — would flip status to published');
      return 'dry';
    }
    await prisma.comparison.update({
      where: { slug },
      data: { status: 'published', publishedAt: new Date(), isHumanReviewed: true },
    });
    console.log(`    published (${existing.id}, status only)`);
    return 'published';
  }

  const data = await fetchComparison(slug);
  const [a, b] = data.entities ?? [];
  if (!a || !b) throw new Error('fewer than two entities');

  console.log(`    title   ${data.title}`);
  console.log(`    ${a.name} vs ${b.name}`);
  console.log(`    ${(data.keyDifferences ?? []).length} key differences`);
  if (existing) {
    console.log(`    exists with status "${existing.status}" — will publish`);
    if (existing.isAutoGenerated && !existing.isHumanReviewed) {
      console.log('    NOTE: auto-generated and never human-reviewed. It was archived');
      console.log('          by DAN-1886 for that reason. Read the page before trusting it.');
    }
  }

  if (dryRun) {
    console.log('    DRY RUN — no write');
    return 'dry';
  }

  const typeA = await ensureEntityType(a.entityType);
  const typeB = await ensureEntityType(b.entityType);
  const entityA = await ensureEntity(a, typeA.id);
  const entityB = await ensureEntity(b, typeB.id);

  const row = {
    title: data.title,
    shortAnswer: data.shortAnswer || null,
    keyDifferences: data.keyDifferences ?? [],
    verdict: data.verdict || null,
    category: data.category || null,
    metaTitle: data.metaTitle ?? null,
    metaDescription: data.metaDescription ?? null,
    status: 'published',
    publishedAt: new Date(),
    // Provenance is preserved, not rewritten. Most of these rows really are
    // auto-generated, and flipping the flag to make them publishable would
    // launder that fact out of the database.
    //
    // isHumanReviewed records the one thing that is actually true here: a
    // human decided this specific page should be live. It also has to be set,
    // because DAN-1886 (comparison-service.ts:873) archives
    // isAutoGenerated && !isHumanReviewed on ingestion — without it the page
    // would silently 404 again the next time the slug is re-ingested.
    //
    // That guard exists to keep thin auto-generated pages out of the index, so
    // this should stay a per-page decision. Do not bulk-run it.
    isAutoGenerated: existing?.isAutoGenerated ?? false,
    isHumanReviewed: true,
  };

  const comparison = await prisma.comparison.upsert({
    where: { slug },
    create: { slug, ...row },
    update: row,
  });

  for (const [entity, source] of [
    [entityA, a],
    [entityB, b],
  ]) {
    await prisma.comparisonEntity.upsert({
      where: { comparisonId_entityId: { comparisonId: comparison.id, entityId: entity.id } },
      create: {
        comparisonId: comparison.id,
        entityId: entity.id,
        position: source.position ?? 0,
        pros: source.pros ?? [],
        cons: source.cons ?? [],
        bestFor: source.bestFor ?? null,
      },
      update: {
        position: source.position ?? 0,
        pros: source.pros ?? [],
        cons: source.cons ?? [],
      },
    });
  }

  console.log(`    published (${comparison.id})`);
  return 'published';
}

const results = [];
for (const slug of slugs) {
  try {
    results.push([slug, await publish(slug)]);
  } catch (err) {
    console.error(`    FAILED: ${err.message}`);
    results.push([slug, 'failed']);
  }
}

await prisma.$disconnect();

console.log('\n---');
results.forEach(([s, r]) => console.log(`  ${String(r).padEnd(10)} ${s}`));
if (results.some(([, r]) => r === 'failed')) process.exit(1);
